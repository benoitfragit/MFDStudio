#pragma once

/** @file @brief Pointer routing helpers for nested API LEVEL 1 scroll regions. */

#include <cstddef>
#include <vector>

#include "mfd/apilevel1/ContainerTypes.h"

namespace mfd::api1
{
/** @brief One validated scroll mutation selected by pointer routing. */
struct ContainerScrollRequest
{
    std::size_t sourceIndex = 0U;
    Vec2 offset {};
};

/**
 * @brief Routes wheel and scrollbar input through the resolved container hierarchy.
 *
 * @note The deepest eligible region is tried first. When it cannot move farther
 * in the requested direction, wheel input bubbles to its eligible ancestors.
 */
class ContainerInputRouter final
{
public:
    /**
     * @brief Tests effective visibility, enabled state, viewport bounds and every ancestor clip.
     * @param definitions Authored definitions matching `layouts` source indices.
     * @param layouts Resolved layout generated by the shared layout engine.
     * @param layout Candidate layout node.
     * @param pointer Page-space pointer position.
     * @return `true` when the candidate may receive pointer input.
     */
    [[nodiscard]] bool CanReceivePointer(const std::vector<ContainerDefinition>& definitions,
                                         const std::vector<ContainerLayoutNode>& layouts,
                                         const ContainerLayoutNode& layout,
                                         Vec2 pointer) const noexcept;

    /**
     * @brief Resolves one wheel gesture into a clamped scroll-offset update.
     * @param definitions Authored definitions matching `layouts` source indices.
     * @param layouts Resolved layout generated by the shared layout engine.
     * @param pointer Page-space pointer position.
     * @param wheelDelta Horizontal and vertical wheel deltas.
     * @param logicalStep Logical distance applied per wheel unit.
     * @param request Receives the selected source index and new offset.
     * @return `true` when an enabled visible region can consume the gesture.
     */
    [[nodiscard]] bool RouteWheel(const std::vector<ContainerDefinition>& definitions,
                                  const std::vector<ContainerLayoutNode>& layouts,
                                  Vec2 pointer,
                                  Vec2 wheelDelta,
                                  float logicalStep,
                                  ContainerScrollRequest& request) const noexcept;

    /**
     * @brief Converts an absolute thumb-center coordinate into a clamped offset.
     * @param layout Resolved scroll geometry.
     * @param horizontal Selects the horizontal axis when `true`.
     * @param thumbCenterCoordinate Desired page-space thumb-center coordinate.
     * @return New axis offset, or the current offset when the track cannot move.
     */
    [[nodiscard]] float OffsetForThumb(const ContainerLayoutNode& layout,
                                       bool horizontal,
                                       float thumbCenterCoordinate) const noexcept;
};
} // namespace mfd::api1
